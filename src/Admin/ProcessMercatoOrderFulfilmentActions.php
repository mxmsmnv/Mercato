<?php
namespace ProcessWire;

trait ProcessMercatoOrderFulfilmentActions {

    protected function handleReservationCleanup(Mercato $commerce): array {
        if ((string) $this->wire('input')->post->text('mrc_cleanup_reservations') !== '1') {
            return [];
        }
        if (!$this->hasCommercePermission(self::PERMISSION_MANAGE_INVENTORY)) {
            return $this->permissionError(self::PERMISSION_MANAGE_INVENTORY, $this->_('Reservation cleanup was blocked.'));
        }

        if (!$this->validateCsrf()) {
            return [
                'summary' => $this->_('Reservation cleanup was blocked. Refresh the page and try again.'),
                'errors' => [$this->_('CSRF token validation failed.')],
            ];
        }

        $count = $commerce->orderRepository()->cleanupExpiredReservations();
        $summary = sprintf($this->_('Released %d expired reservation(s).'), $count);
        $this->wire('session')->message($summary);

        return [
            'summary' => $summary,
            'released' => $count,
            'errors' => [],
        ];
    }

    protected function handleDemoOrderCreation(Mercato $commerce): array {
        if ((string) $this->wire('input')->post->text('mrc_create_demo_order') !== '1') {
            return [];
        }
        if (!$this->hasCommercePermission(self::PERMISSION_LAUNCH_TOOLS)) {
            return $this->permissionError(self::PERMISSION_LAUNCH_TOOLS, $this->_('Demo order creation was blocked.'));
        }

        if (!$this->validateCsrf()) {
            return [
                'summary' => $this->_('Demo order creation was blocked. Refresh the page and try again.'),
                'errors' => [$this->_('CSRF token validation failed.')],
            ];
        }

        if (!empty($commerce->production)) {
            return [
                'summary' => $this->_('Demo order creation is disabled in production mode.'),
                'errors' => [$this->_('Switch to test mode before creating workflow fixtures.')],
            ];
        }

        $product = $this->wire('pages')->get('template=mrc-product, name=ceramics-gift-card, include=all');
        if (!$product || !$product->id) {
            return [
                'summary' => $this->_('Demo order creation failed.'),
                'errors' => [$this->_('Ceramics Gift Card product is missing. Run Mercato installer/repair first.')],
            ];
        }

        $items = $commerce->productList([
            ['id' => (int) $product->id, 'quantity' => 1],
        ])->toArray();
        $cart = $commerce->productList($items);
        $method = strtolower(trim((string) $this->wire('input')->post->text('demo_fulfilment_method')));
        if (!MercatoFulfilmentMethodType::isValid($method)) {
            $method = MercatoFulfilmentMethodType::CARRIER_DELIVERY;
        }
        $snapshot = $this->getDemoFulfilmentSnapshot($commerce, $cart, $method);
        $subtotal = (float) $product->mrc_price;
        $shipping = (float) $snapshot['amount'];
        $total = round($subtotal + $shipping, 2);
        $order = $commerce->orderRepository()->savePendingOrder([
            'first_name' => 'Demo',
            'last_name' => 'Customer',
            'email' => 'demo-order@example.test',
            'notes' => 'Generated by Mercato launch checklist for fulfilment testing. No live payment was processed.',
            'payment_method' => 'demo',
            'payment_status' => Mercato::PAYMENT_STATUS_PAID,
            'payment_complete' => 1,
            'paid_date' => date('Y-m-d H:i:s'),
            'payment_details' => json_encode(['demo' => true, 'source' => 'launch_checklist']),
            'mrc_receipt_details' => json_encode($commerce->buildReceiptDetailsSnapshot($cart, $shipping), JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE),
            'mrc_items' => json_encode($items, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE),
            'mrc_currency' => (string) $commerce->currency,
            'mrc_subtotal_amount' => $subtotal,
            'mrc_shipping_amount' => $shipping,
            'fulfilment_method' => $snapshot['type'],
            'mrc_fulfilment_label' => $snapshot['label'],
            'mrc_fulfilment_details' => json_encode($snapshot, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE),
            'mrc_discount_total' => 0,
            'mrc_total_amount' => $total,
        ]);

        $summary = sprintf($this->_('Created demo paid order %s for %s testing.'), (string) $order->mrc_invoice_number, (string) $snapshot['label']);
        $this->wire('session')->message($summary);
        return [
            'summary' => $summary,
            'order' => $order,
            'errors' => [],
        ];
    }

