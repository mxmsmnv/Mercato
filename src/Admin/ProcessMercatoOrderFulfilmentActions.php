            return [
                'summary' => $this->_('Demo checkout configuration was blocked. Refresh the page and try again.'),
                'errors' => [$this->_('CSRF token validation failed.')],
            ];
        }

        if (!empty($commerce->production)) {
            return [
                'summary' => $this->_('Demo checkout configuration is disabled in production mode.'),
                'errors' => [$this->_('Switch to test mode before enabling demo receiving methods.')],
            ];
        }

        $modules = $this->wire('modules');
        $config = array_merge(Mercato::getDefaultConfig(), (array) $modules->getConfig('Mercato'));
        $updates = [
            'enabled_fulfilment_methods' => [
                MercatoFulfilmentMethodType::CARRIER_DELIVERY,
